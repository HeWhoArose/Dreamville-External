import { test } from 'node:test';
import assert from 'node:assert/strict';
import { InMemoryWorldRepository } from '../server/repositories/worldRepository';
import { EmergentNarrativeEngine, describeEmergentThread } from '../server/services/emergentNarrativeEngine';

/**
 * V2 gap G8: emergent threads used to be titled "Emergent Thread: <event> at <internal location id>"
 * and that text reached the model-facing open-thread list. Thread wording must come from the committed
 * event and the location's display name, never an internal ID or a mechanical placeholder.
 */
function event(storyId: string, locationId: string, eventType = 'INVESTIGATE_AREA') {
  return { eventId: `evt_${locationId}`, storyId, eventType, actorId: 'player', locationId, details: 'x', timestamp: '2026-11-23T00:00:00.000Z' };
}

test('thread wording uses the location display name and no internal id or placeholder', () => {
  const repo = new InMemoryWorldRepository({ disablePersistence: true });
  const storyId = 'emergent_title_story';
  repo.seedStory(storyId);
  repo.getGeographyGraph(storyId).addNode({
    id: 'loc_warehouse_docks', name: 'Warehouse Docks', regionId: 'r', description: 'd', archetype: 'CRIME_SCENE',
    accessible: true, discovered: true, sceneObjects: [],
  } as any);

  const result = new EmergentNarrativeEngine().processCanonicalEvent(event(storyId, 'loc_warehouse_docks'), repo);
  const thread = result.createdThread!;
  assert.ok(thread, 'a thread must be created');
  assert.equal(thread.title, 'Investigate area at Warehouse Docks');
  assert.equal(thread.description, 'Follow up on the investigate area at Warehouse Docks.');
  for (const text of [thread.title, thread.description || '']) {
    assert.doesNotMatch(text, /loc_[a-z_]+/i, 'internal location id leaked');
    assert.doesNotMatch(text, /Emergent Thread|generated by server/i, 'mechanical placeholder leaked');
  }
  assert.equal(thread.locationId, 'loc_warehouse_docks', 'canonical locationId is still stored for matching');
});

test('an unknown or missing location falls back to neutral wording, never the raw id', () => {
  const repo = new InMemoryWorldRepository({ disablePersistence: true });
  const storyId = 'emergent_title_unknown';
  repo.seedStory(storyId);
  const unknown = new EmergentNarrativeEngine().processCanonicalEvent(event(storyId, 'loc_never_defined'), repo).createdThread!;
  assert.equal(unknown.title, 'Investigate area at an unrecorded location');
  assert.doesNotMatch(unknown.title + unknown.description, /loc_never_defined/);
  assert.deepEqual(describeEmergentThread('SEARCH', undefined), {
    title: 'Search at an unrecorded location',
    description: 'Follow up on the search at an unrecorded location.',
  });
});

test('thread stage still advances on a repeat event at the same location', () => {
  const repo = new InMemoryWorldRepository({ disablePersistence: true });
  const storyId = 'emergent_title_advance';
  repo.seedStory(storyId);
  const engine = new EmergentNarrativeEngine();
  engine.processCanonicalEvent(event(storyId, 'loc_a'), repo);
  const second = engine.processCanonicalEvent({ ...event(storyId, 'loc_a'), eventId: 'evt_second' }, repo);
  assert.ok(second.updatedThread, 'matching thread must be advanced, not duplicated');
  assert.equal(second.updatedThread!.stage, 2);
});
